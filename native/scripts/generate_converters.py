"""Regenerate typed converters from the contract and the locked Rust SDK source.

Run from any directory with the pinned Cargo toolchain available. The generated
code is compiled, shipped and reviewed; this generator never runs at import or
request time. --check is suitable for CI and detects model or SDK drift.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

NATIVE = Path(__file__).resolve().parents[1]


def snake(name: str) -> str:
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()


def generate(sdk: Path) -> str:
    model = json.loads((NATIVE.parent / "tests/contract/manifest.json").read_text())
    shapes = model["shapes"]
    operations = model["operations"]
    roots = {v[k]: op for op, v in operations.items() for k in ("input", "output")}
    visited: set[str] = set()

    def visit(name: str) -> None:
        if name in visited:
            return
        visited.add(name)
        s = shapes[name]
        for child in s.get("members", {}).values():
            visit(child)
        for key in ("member", "key", "value"):
            if key in s:
                visit(s[key])

    for root in roots:
        visit(root)

    def typ(name: str) -> str:
        s = shapes[name]
        t = s["type"]
        if t == "structure" or "enum" in s:
            if name in roots:
                return f"aws_sdk_dynamodb::operation::{snake(roots[name])}::{name}"
            return f"aws_sdk_dynamodb::types::{name}"
        if t == "list":
            return f"Vec<{typ(s['member'])}>"
        if t == "map":
            return f"HashMap<String, {typ(s['value'])}>"
        return {
            "string": "String",
            "blob": "Blob",
            "boolean": "bool",
            "integer": "i32",
            "long": "i64",
            "double": "f64",
        }[t]

    def source(name: str) -> str:
        if name in roots:
            path = sdk / "src/operation" / snake(roots[name]) / f"_{snake(name)}.rs"
        else:
            path = sdk / "src/types" / f"_{snake(name)}.rs"
        return path.read_text()

    def optional(name: str, field: str) -> bool:
        member = re.search(rf"pub {snake(field)}:\s*([^\n]+)", source(name))
        if member is None:
            raise RuntimeError(f"SDK does not contain {name}.{field}")
        return member[1].startswith("::std::option::Option")

    def presence_route(name: str) -> str | None:
        shape = shapes[name]
        kind = shape["type"]
        # AttributeValue's tagged writer has no presence guards; never traverse
        # its recursive maps/lists or retain its potentially large leaf values.
        if name == "AttributeValue":
            return None
        if kind == "structure":
            fields = []
            for field, child in shape["members"].items():
                route = presence_route(child)
                if route is None and not optional(name, field):
                    route = "Presence::Marker"
                if route is not None:
                    fields.append(f'("{field}", {route})')
            return "Presence::Object(&[" + ", ".join(fields) + "])" if fields else None
        if kind in ("map", "list"):
            child = presence_route(shape["value" if kind == "map" else "member"])
            if child is not None:
                return f"Presence::{kind.title()}(&{child})"
        return None

    lines = [
        "// Copyright ScyllaDB, Inc.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by native/scripts/generate_converters.py. Do not edit by hand.",
        "use super::*;",
        "",
    ]
    for name in sorted(visited):
        s = shapes[name]
        t = s["type"]
        fn = snake(name)
        rt = typ(name)
        lines.append(
            f"pub(super) fn read_{fn}(v: &Bound<'_, PyAny>, path: &dyn Display, depth: usize) -> PyResult<{rt}> {{"
        )
        lines.append("    check_depth(path, depth)?;")
        if t == "structure":
            lines.append("    let v = dictionary(v, path, depth)?;")
            fields = ", ".join(json.dumps(f) for f in s["members"])
            required = ", ".join(json.dumps(f) for f in s["required"])
            lines.append(f"    members(&v, &[{fields}], &[{required}], path)?;")
            if name == "AttributeValue":
                lines.append(
                    '    if v.len() != 1 { return Err(validation(path, "AttributeValue must contain exactly one type member")); }'
                )
                lines.append("    match v.iter().next() {")
                for field, child in s["members"].items():
                    variant = {
                        "BOOL": "Bool",
                        "NULL": "Null",
                        "SS": "Ss",
                        "NS": "Ns",
                        "BS": "Bs",
                    }.get(field, field)
                    lines.append(
                        f'        Some((key, value)) if key.extract::<String>()? == "{field}" => Ok({rt}::{variant}(read_{snake(child)}(&value, &format_args!("{{path}}.{field}"), depth + 1)?)),'
                    )
                lines.append(
                    '        _ => Err(validation(path, "unknown AttributeValue type")),\n    }'
                )
            else:
                lines.append(f"    let mut builder = {rt}::builder();")
                for field, child in s["members"].items():
                    # RequestItems maps also appear as response unprocessed maps,
                    # where explicit emptiness is valid. Enforce their request
                    # minimum at the input member rather than in the shared reader.
                    child_shape = shapes[child]
                    if (
                        name.endswith("Input")
                        and child_shape["type"] == "map"
                        and "min" in child_shape
                    ):
                        lines.append(
                            f'    if let Some(value) = v.get_item("{field}")? {{ length(&format_args!("{{path}}.{field}"), dictionary(&value, &format_args!("{{path}}.{field}"), depth + 1)?.len(), {option(child_shape.get("min"))}, None)?; }}'
                        )
                    lines.append(
                        f'    if let Some(value) = v.get_item("{field}")? {{ builder = builder.set_{snake(field)}(Some(read_{snake(child)}(&value, &format_args!("{{path}}.{field}"), depth + 1)?)); }}'
                    )
                lines.append("    builder.build().finish(path)")
        elif t == "map":
            lines.extend(
                [
                    "    let v = dictionary(v, path, depth)?;",
                    "    let mut result = HashMap::new();",
                    "    for (key, value) in v.iter() {",
                    f"        let key = read_{snake(s['key'])}(&key, path, depth + 1)?;",
                    f'        let value = read_{snake(s["value"])}(&value, &format_args!("{{path}}[{{key:?}}]"), depth + 1)?;',
                    "        result.insert(key, value);",
                    "    }",
                ]
            )
            lines.append("    Ok(result)")
        elif t == "list":
            lines.append("    let v = sequence(v, path, depth)?;")
            if "min" in s:
                lines.append(
                    f"    length(path, v.len(), {option(s.get('min'))}, None)?;"
                )
            lines.append(
                f'    v.enumerate().map(|(i, v)| read_{snake(s["member"])}(&v, &format_args!("{{path}}[{{i}}]"), depth + 1)).collect()'
            )
        else:
            func = t if t != "string" or "enum" not in s else "string"
            lines.append(f"    let result = {func}(v, path)?;")
            if t == "string" and "min" in s:
                lines.append(
                    f"    length(path, result.chars().count(), {option(s.get('min'))}, None)?;"
                )
            if t in ("integer", "long", "double"):
                checks = []
                if "min" in s:
                    checks.append(f"result < {s['min']}")
                if checks:
                    lines.append(
                        f'    if {" || ".join(checks)} {{ return Err(validation(path, "value outside modeled range")); }}'
                    )
            lines.append(
                f"    Ok({rt}::from(result.as_str()))"
                if "enum" in s
                else "    Ok(result)"
            )
        lines.append("}\n")
        write_rt = f"[{typ(s['member'])}]" if t == "list" else rt
        lines.append(
            f"pub(super) fn write_{fn}<'py>(py: Python<'py>, v: &{write_rt}, presence: Option<&Value>) -> PyResult<Bound<'py, PyAny>> {{"
        )
        if t == "structure":
            lines.append("    let result = PyDict::new(py);")
            if name == "AttributeValue":
                lines.append("    match v {")
                for field, child in s["members"].items():
                    variant = {
                        "BOOL": "Bool",
                        "NULL": "Null",
                        "SS": "Ss",
                        "NS": "Ns",
                        "BS": "Bs",
                    }.get(field, field)
                    lines.append(
                        f'        {rt}::{variant}(v) => result.set_item("{field}", write_{snake(child)}(py, v, presence.and_then(|p| p.get("{field}")))?)?,'
                    )
                lines.append("        _ if v.is_unknown() => {},")
                lines.append(
                    '        _ => return Err(PyRuntimeError::new_err("unrepresentable SDK AttributeValue variant")),\n    }'
                )
            else:
                for field, child in s["members"].items():
                    sf = snake(field)
                    expr = f'write_{snake(child)}(py, value, presence.and_then(|p| p.get("{field}")))?'
                    if optional(name, field):
                        lines.append(
                            f'    if let Some(value) = &v.{sf} {{ result.set_item("{field}", {expr})?; }}'
                        )
                    else:
                        lines.append(
                            f'    if scalar_present(presence, "{field}") {{ let value = &v.{sf}; result.set_item("{field}", {expr})?; }}'
                        )
            lines.append("    Ok(result.into_any())")
        elif t == "map":
            lines.extend(
                [
                    "    let result = PyDict::new(py);",
                    "    for (key, value) in v {",
                    f"        result.set_item(write_{snake(s['key'])}(py, key, None)?, write_{snake(s['value'])}(py, value, presence.and_then(|p| p.get(key)))?)?;",
                    "    }",
                    "    Ok(result.into_any())",
                ]
            )
        elif t == "list":
            lines.extend(
                [
                    "    let result = PyList::empty(py);",
                    "    for (i, value) in v.iter().enumerate() {",
                    f"        result.append(write_{snake(s['member'])}(py, value, presence.and_then(|p| p.get(i)))?)?;",
                    "    }",
                    "    Ok(result.into_any())",
                ]
            )
        elif t == "blob":
            lines.append(
                "    let _ = presence;\n    Ok(PyBytes::new(py, v.as_ref()).into_any())"
            )
        else:
            lines.append("    let _ = presence;")
            expr = "v.as_str()" if "enum" in s else "v"
            lines.append(f"    Ok({expr}.into_pyobject(py)?.to_owned().into_any())")
        lines.append("}\n")

    for kind in ("Input", "Output"):
        lines.append(f"#[derive(Debug)]\npub enum {kind} {{")
        for op, spec in operations.items():
            lines.append(f"    {op}(Box<{typ(spec[kind.lower()])}>),")
        lines.append("}\n")
        lines.append(f"impl {kind} {{")
        lines.append(
            "    pub fn from_python(operation: &str, value: &Bound<'_, PyAny>) -> PyResult<Self> {\n        match operation {"
        )
        for op, spec in operations.items():
            lines.append(
                f'            "{op}" => Ok(Self::{op}(Box::new(read_{snake(spec[kind.lower()])}(value, &"{op}", 0)?))),'
            )
        lines.append(
            '            _ => Err(PyNotImplementedError::new_err(format!("unsupported native operation: {operation}"))),\n        }\n    }'
        )
        # Input round-trip is useful for differential tests; Output requires wire
        # presence from its own final operation response.
        lines.append(
            "    pub fn to_python<'py>(&self, py: Python<'py>, presence: Option<&Value>) -> PyResult<Bound<'py, PyAny>> {\n        match self {"
        )
        for op, spec in operations.items():
            lines.append(
                f"            Self::{op}(value) => write_{snake(spec[kind.lower()])}(py, value, presence),"
            )
        lines.append("        }\n    }")
        if kind == "Output":
            lines.append(
                "    pub(crate) fn presence_route(&self) -> &'static crate::response::Presence {\n        use crate::response::Presence;\n        match self {"
            )
            for op, spec in operations.items():
                route = presence_route(spec["output"]) or "Presence::Object(&[])"
                lines.append(f"            Self::{op}(_) => &{route},")
            lines.append("        }\n    }")
        lines.append("}")
    return "\n".join(lines) + "\n"


def option(value: int | None) -> str:
    return "None" if value is None else f"Some({value})"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--locked", "--format-version", "1"], cwd=NATIVE
        )
    )
    sdk = next(p for p in metadata["packages"] if p["name"] == "aws-sdk-dynamodb")
    content = generate(Path(sdk["manifest_path"]).parent)
    # Use the repository's pinned formatter, including for --check.
    formatted = subprocess.check_output(
        ["rustfmt", "--edition", "2021"], input=content.encode(), cwd=NATIVE
    )
    target = NATIVE / "src/conversion/generated.rs"
    if args.check:
        if target.read_bytes() != formatted:
            raise SystemExit(
                "converters differ; run native/scripts/generate_converters.py"
            )
    else:
        target.write_bytes(formatted)


if __name__ == "__main__":
    main()
